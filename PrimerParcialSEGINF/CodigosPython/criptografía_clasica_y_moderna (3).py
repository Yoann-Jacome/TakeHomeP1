# Creación funcion de cifrado vigenere
def cifrado_vigenere(texto, clave, modo='cifrar'):
    resultado = ""
    clave = clave.upper()
    j = 0  # índice para recorrer la clave

    for caracter in texto: # Ciclo for para iterar la cantidad de veces necesaria la clave para completar el mensaje
        if caracter.isalpha():
            base = ord('A') if caracter.isupper() else ord('a')
            desplazamiento = ord(clave[j % len(clave)]) - ord('A')

            if modo == 'descifrar': # Se define el modo de descrifrar con la funcionalidad de devolver la cantidad de casillas desplazadas en el corrimiento
                desplazamiento = -desplazamiento

            nuevo = (ord(caracter) - base + desplazamiento) % 26
            resultado += chr(base + nuevo)
            j += 1
        else:
            resultado += caracter

    return resultado

# Cifrar
