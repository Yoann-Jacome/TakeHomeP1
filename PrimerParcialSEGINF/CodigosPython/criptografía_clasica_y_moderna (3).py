# Creación funcion de cifrado cesar, con los siguientes parametros:
# Texto: Mensaje original a cifrar
# Desplazamiento: Entero con cantidad de corrimientos en el abecedario
def cifrado_cesar(texto, desplazamiento):
    resultado = ""
    # Se implementa un for para iterar en el abecedario la cantidad de veces requeridas para cifrar el mensaje
    for caracter in texto:
        if caracter.isalpha(): # se verifica que el mensaje este con valores alpha numericos
            base = ord('A') if caracter.isupper() else ord('a')
            nuevo = (ord(caracter) - base + desplazamiento) % 26 # Se desplaza los caracteres del mensaje segun el valor de desplazamiento
            resultado += chr(base + nuevo)
        else:
            resultado += caracter
    return resultado

