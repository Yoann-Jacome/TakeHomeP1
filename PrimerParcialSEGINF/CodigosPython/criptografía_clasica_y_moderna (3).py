"""c. Cifrado simétrico moderno (Fernet/AES)"""

# Re utilización del codigo brindado por el docente en la sesion 3
#Importacion libreria cryptography
from Crypto.Cipher import AES
from Crypto.Util.Padding import pad, unpad
from Crypto.Random import get_random_bytes
import binascii

# Generar una llave de 16 bytes (128 bits)
llave = get_random_bytes(16)
mensaje = "Este es un mensaje de prueba AES."
mensaje_bytes = mensaje.encode('utf-8')

# MODO ECB
cifrador_ecb = AES.new(llave, AES.MODE_ECB) # Se crea una variable cifradora que contiene la llave y el modo
cifrado_ecb = cifrador_ecb.encrypt(pad(mensaje_bytes, 16)) # Cifra el mensaje y lo rellena para que su longitud sea múltiplo de 16 bytes antes de cifrar
print("MODO ECB: ")
print(f"Cifrado (hex): {binascii.hexlify(cifrado_ecb).decode()}") # Se imprime el resultado en hexadecimal

# Descifrar ECB
descifrador_ecb = AES.new(llave, AES.MODE_ECB) # Se crea la variable descifradora haciendo uso de la llave y el mismo modo
descifrado_ecb = unpad(descifrador_ecb.decrypt(cifrado_ecb), 16) # Quita el relleno que se agregó antes de cifrar, para recuperar el mensaje original exacto.
print(f"Descifrado: {descifrado_ecb.decode()}") # Se imprime el resultado del mensaje descifrado

# MODO CBC
iv = get_random_bytes(16)  # Vector de inicialización
# Se cifra el mensaje con la llave y haciendo uso del vector de inicializacion para combinar con el primer bloque y romper la similitud en caso de tener el mismo valor,
# Luego cada bloque cifrado se combina con el bloque anterior antes de cifrar el siguiente
cifrador_cbc = AES.new(llave, AES.MODE_CBC, iv=iv)
cifrado_cbc = cifrador_cbc.encrypt(pad(mensaje_bytes, 16)) #Cifra el mensaje y lo rellena para que su longitud sea múltiplo de 16 bytes antes de cifrar
print("MODO CBC: ")
print(f"Cifrado (hex): {binascii.hexlify(cifrado_cbc).decode()}")

# Descifrar CBC
# Para descifrar el mensaje se hace uso del mismo iv, para poder descrifrar correctamente
descifrador_cbc = AES.new(llave, AES.MODE_CBC, iv=iv)
descifrado_cbc = unpad(descifrador_cbc.decrypt(cifrado_cbc), 16) # Quita el relleno que se agregó antes de cifrar, para recuperar el mensaje original exacto.
print(f"Descifrado: {descifrado_cbc.decode()}") # Se imprime el resultado del mensaje descifrado