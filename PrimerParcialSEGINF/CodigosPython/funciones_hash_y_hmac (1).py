import hashlib

# Funcion para calcular el hash SHA-256 de un archivo, tomando como parametro el nombre del archivo
def hash_archivo(nombre_archivo):
  # Se crea primero un objeto hash vacío, ideal para archivos grandes: no hace falta cargar todo el archivo en memoria de una vez.
    sha256 = hashlib.sha256()
    with open(nombre_archivo, 'rb') as f: #abre el archivo en modo 'rb' (read binary)
        while True: #Ciclo while para leer el contenido interno del archivo por partes
            bloque = f.read(4096) # Lee el siguiente pedazo del archivo, de máximo 4096 bytes (4 KB).
            if not bloque: # Si se detecta falta de contenido en la lectura se detiene el bucle
                break
            sha256.update(bloque)
    return sha256.hexdigest() # Retorna el resultado final del hash

# Prueba de calculo del hash
