"""c. HMAC"""

# Se importa la libreria hmac y hashlib
import hmac
import hashlib

def generar_hmac(mensaje: str, clave: str) -> str: # La flecha, indica el tipo de dato que va a devolver, en este caso un string, que será el código HMAC final en formato hexadecimal
    # Genera el código HMAC-SHA256 en formato hexadecimal
    # Convertir el mensaje y la clave a bytes
    clave_bytes = clave.encode('utf-8')
    mensaje_bytes = mensaje.encode('utf-8')

    # Crear el objeto HMAC con la clave, el mensaje y el algoritmo SHA-256
    objeto_hmac = hmac.new(clave_bytes, mensaje_bytes, hashlib.sha256)

    # Retornar la firma en formato hexadecimal
    return objeto_hmac.hexdigest()

def verificar_hmac(mensaje: str, clave: str, firma_recibida: str) -> bool: # La flecha -> indica qué tipo de dato va a devolver un bool, que será la verificacion de si la firma recibida coincide con el mensaje y la clave
    # Verifica si la firma recibida coincide con el mensaje y la clave
    # Generar una nueva firma local usando los mismos datos
    firma_esperada = generar_hmac(mensaje, clave)

    return firma_esperada == firma_recibida

